const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const path = require('node:path');
const api = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src/lib/suivi/repcount-session.ts'), 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText, {exports:api});
const plain = value => JSON.parse(JSON.stringify(value));
assert.deepEqual(plain(api.nomsSeance(null)),[]);
assert.deepEqual(plain(api.nomsSeance([null,{}, {nom:' '}, {nom:'Presse'}, {nom:'Presse'}, {nom:'Presse inclinée'}])),['Presse','Presse inclinée']);
const presse = {nom:'Presse à cuisses', sets:[{reps:12,charge:40}]};
const original = JSON.stringify(presse);
const deux = api.assemblerSeance([presse], 'Gainage planche', [{reps:0,charge:0,dureeSecondes:30}]);
assert.equal(deux.length,2);
assert.equal(deux[1].sets[0].dureeSecondes,30);
const retour = api.assemblerSeance(deux,'Presse à cuisses',[{reps:10,charge:40}]);
assert.equal(retour.length,2);
assert.equal(retour[0].sets.length,2);
assert.equal(JSON.stringify(presse),original);
assert.equal(deux[0].sets.length,1);
assert.equal(api.assemblerSeance(retour,'Presse unilatérale',[{reps:8,charge:20}]).length,3);
assert.deepEqual(plain(api.payloadSeance(retour)).map(ex=>ex.sets.map(s=>s.set)), [[1,2],[1]]);
assert.deepEqual(plain(api.assemblerSeance(retour,'',[])), plain(retour));
assert.deepEqual(plain(api.assemblerSeance([], 'Vide', [])), []);
console.log('PASS RepCount session: plusieurs exercices, retour au même mouvement, variantes séparées, maintien, ordre et numérotation, aucune mutation');
