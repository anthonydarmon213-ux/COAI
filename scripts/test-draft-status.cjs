const assert = require('node:assert/strict');
const fs = require('node:fs'), vm = require('node:vm'), ts = require('typescript');
const out = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/lib/suivi/draft-status.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText, {exports:out});
const a = out.createDraftStatus(), b = out.createDraftStatus();
let changes = 0;
const unsubscribe = a.subscribe(() => changes++);
assert.equal(a.snapshot(), false);
a.report(true);
assert.equal(a.snapshot(), true);
assert.equal(a.serverSnapshot(), false);
assert.equal(b.snapshot(), false);
a.report(true);
assert.equal(changes, 1);
a.report(false);
assert.equal(changes, 2);
unsubscribe();
a.report(true);
assert.equal(changes, 2);
console.log('PASS draft status: isolated editors, failure/recovery, stable snapshots and cleanup.');
