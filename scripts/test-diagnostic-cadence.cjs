const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const source = fs.readFileSync(require("node:path").join(__dirname, "../src/lib/email/diagnostic-cadence.ts"), "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const sandbox = { exports: {} };
vm.runInNewContext(compiled, sandbox);
const { canSendDiagnosticReminder: due } = sandbox.exports;
const now = Date.parse("2026-09-07T10:00:00Z");
const empty = () => ({ conversionReminderSentAt: null, drip3SentAt: null, drip5SentAt: null, drip7SentAt: null });
assert.equal(due([empty()], "drip3SentAt", now), true);
const sent = { ...empty(), drip3SentAt: new Date(now) };
assert.equal(due([sent], "drip5SentAt", now), false);
assert.equal(due([sent], "drip7SentAt", now), false);
assert.equal(due([sent], "conversionReminderSentAt", now), false);
assert.equal(due([empty(), sent], "drip3SentAt", now + 7 * 86400000), false);
assert.equal(due([sent], "drip5SentAt", now + 48 * 3600000 - 1), false);
assert.equal(due([sent], "drip5SentAt", now + 48 * 3600000), true);
assert.equal(due([sent], "drip5SentAt", now - 1), false);
console.log("PASS: 8 diagnostic cadence cases (catch-up, duplicate leads, spacing boundary, clock skew)");
